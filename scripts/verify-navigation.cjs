const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless: true});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, locale: 'zh-CN'});
  const page = await context.newPage();
  const errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push({type: request.resourceType(), url: request.url()}));
  const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:4322';
  await page.goto(base + '/');
  await page.waitForFunction(() => document.querySelector('#resume-preview')?.dataset.fontStatus === 'ready');
  assert.equal(await page.locator('.app-header').count(), 1);
  const heading = await page.locator('.app-header h1').textContent();
  await page.evaluate(() => { window.originalHeader = document.querySelector('.app-header'); window.originalDocument = document; });
  const markdown = '# 同页编辑测试\n\n这是保留的職務経歴書内容。';
  await page.locator('#markdown-input').fill(markdown);
  await page.locator('#career-workspace [data-theme-option="forest"]').click();
  await page.locator('#personal-tab').click();
  await page.waitForFunction(() => document.querySelectorAll('.r-sheet').length > 0 && !document.querySelector('#r-print').disabled);
  assert.equal(await page.locator('.app-header h1').textContent(), heading);
  await page.locator('[name="name"]').fill('共用工作台 测试');
  await page.locator('#personal-workspace [data-theme-option="burgundy"]').click();
  await page.locator('#r-font').selectOption('noto-serif-jp');
  await page.waitForFunction(() => !document.querySelector('#r-print').disabled);
  await page.evaluate(() => { window.personalInput = document.querySelector('[name="name"]'); window.personalPage = document.querySelector('.r-sheet'); });
  const loadedRequests = requests.length;
  const switches = [];
  for (let i = 0; i < 12; i++) {
    const mode = i % 2 ? 'personal' : 'career';
    const time = await page.evaluate(mode => { const start = performance.now(); document.getElementById(mode + '-tab').click(); return performance.now() - start; }, mode);
    assert.equal(await page.locator('#' + mode + '-workspace').isVisible(), true);
    assert.equal(await page.locator('.workspace:visible').count(), 1);
    assert.ok(await page.evaluate(() => document === window.originalDocument && document.querySelector('.app-header') === window.originalHeader));
    switches.push({mode, milliseconds: +time.toFixed(2)});
  }
  assert.equal(requests.slice(loadedRequests).filter(request => request.type === 'document' || request.type === 'script').length, 0);
  assert.equal(await page.locator('[name="name"]').inputValue(), '共用工作台 测试');
  assert.ok(await page.evaluate(() => document.querySelector('[name="name"]') === window.personalInput && document.querySelector('.r-sheet') === window.personalPage));
  assert.equal(await page.locator('#personal-workspace [data-theme-option="burgundy"]').getAttribute('aria-pressed'), 'true');
  await page.locator('#career-tab').click();
  assert.equal(await page.locator('#markdown-input').inputValue(), markdown);
  assert.equal(await page.locator('#career-workspace [data-theme-option="forest"]').getAttribute('aria-pressed'), 'true');
  await page.waitForFunction(() => document.querySelector('#resume-preview').dataset.fontStatus === 'ready');
  await page.evaluate(() => { window.printCalls = 0; window.print = () => { window.printCalls++; }; });
  await page.keyboard.press('Control+p');
  await page.waitForFunction(() => window.printCalls === 1);
  fs.mkdirSync('artifacts/navigation', {recursive: true});
  const expectedCareerPages = await page.locator('.resume-page').count();
  const careerPdf = await page.pdf({path: 'artifacts/navigation/career-only.pdf', format: 'A4', printBackground: true, preferCSSPageSize: true});
  assert.equal((careerPdf.toString('latin1').match(/\/Type\s*\/Page\b/g) || []).length, expectedCareerPages, 'The hidden personal document is excluded from print');
  await page.locator('#career-tab').press('ArrowRight');
  assert.equal(await page.locator('#personal-workspace').isVisible(), true);
  await page.keyboard.press('Control+p');
  await page.waitForFunction(() => window.printCalls === 2);
  await page.goBack();
  assert.equal(await page.locator('#career-workspace').isVisible(), true);
  await page.goForward();
  assert.equal(await page.locator('#personal-workspace').isVisible(), true);
  await page.locator('[data-locale-option="en"]').click();
  assert.equal(await page.locator('#r-print').textContent(), 'Save as PDF');
  await page.evaluate(() => scrollTo(0, 0));
  await page.locator('#career-tab').click();
  assert.equal(await page.locator('#save-pdf').textContent(), 'Save as PDF');
  await page.locator('#personal-tab').click();
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#personal-workspace').hidden === false && !document.querySelector('#r-print').disabled);
  assert.equal(await page.locator('[name="name"]').inputValue(), '共用工作台 测试');
  assert.equal(await page.locator('#r-font').inputValue(), 'noto-serif-jp');
  assert.equal(await page.locator('#r-print').textContent(), 'Save as PDF');
  fs.mkdirSync('artifacts/navigation', {recursive: true});
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({path: 'artifacts/navigation/single-workbench-desktop.png', fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: 'artifacts/navigation/single-workbench-mobile.png', fullPage: true});
  assert.ok(await page.evaluate(() => document.body.scrollWidth <= innerWidth));
  console.log('mobile page extent', await page.evaluate(() => ({document: document.documentElement.scrollHeight, app: document.querySelector('.app').getBoundingClientRect().height})));
  assert.deepEqual(errors, []);
  const legacyPage = await context.newPage();
  await legacyPage.goto(base + '/rirekisho/');
  await legacyPage.waitForURL(base + '/#rirekisho');
  await legacyPage.waitForFunction(() => !document.querySelector('#personal-workspace').hidden);
  assert.equal(await legacyPage.locator('.app-header').count(), 1);
  await legacyPage.close();
  console.log(JSON.stringify({switches, newDocumentRequests: 0, errors}, null, 2));
  await browser.close();
})().catch(error => {console.error(error); process.exit(1);});
