const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({headless: true});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, locale: 'zh-CN', hasTouch: true});
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4322/#rirekisho');
  await page.waitForFunction(() => document.querySelectorAll('.r-sheet').length > 0);
  assert.equal(await page.locator('#r-edit-photo').isDisabled(), true);
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('rirekisho-draft-v1') || '{}'));
  const upload = async () => {
    await page.locator('#r-photo').setInputFiles(path.resolve('src/assets/demo-avatar-512.webp'));
    await page.locator('#r-avatar-editor[open]').waitFor();
    await page.waitForFunction(() => !document.querySelector('#save-r-avatar-editor').disabled);
  };
  await upload();
  assert.equal(await page.locator('.r-id-photo img').count(), 0, 'Uploading does not commit before Save');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#r-avatar-editor').isVisible(), false);
  assert.equal((await read()).photo || '', '');
  await upload();
  assert.equal(await page.locator('#r-avatar-editor input[type="radio"]').count(), 0);
  const ratio = await page.locator('#r-avatar-editor-crop-window').evaluate(el => el.clientWidth / el.clientHeight);
  assert.ok(Math.abs(ratio - .75) < .01, 'The crop is fixed to 3:4');
  await page.locator('#r-avatar-zoom').fill('160');
  const stage = page.locator('#r-avatar-editor-stage');
  const bounds = await stage.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + 18, bounds.y + bounds.height / 2 + 12); await page.mouse.up();
  const editorTransform = await page.locator('#r-avatar-editor-image').evaluate(el => { const matrix = new DOMMatrix(getComputedStyle(el).transform); return {zoom: matrix.a, x: matrix.e / el.clientWidth, y: matrix.f / el.clientHeight}; });
  fs.mkdirSync('artifacts/photo-editor', {recursive: true});
  await page.screenshot({path: 'artifacts/photo-editor/desktop-modal.png'});
  await page.locator('#save-r-avatar-editor').click();
  const saved = await read();
  assert.equal(saved.zoom, 160); assert.ok(saved.photoX > 0 && saved.photoY > 0);
  const previewTransform = await page.locator('.r-id-photo img').evaluate(el => { const matrix = new DOMMatrix(getComputedStyle(el).transform); return {zoom: matrix.a, x: matrix.e / el.clientWidth, y: matrix.f / el.clientHeight}; });
  for (const key of ['zoom', 'x', 'y']) assert.ok(Math.abs(editorTransform[key] - previewTransform[key]) < .001, `${key}: preview matches the editor`);
  await page.locator('#r-edit-photo').click();
  assert.equal(await page.locator('#r-avatar-zoom').inputValue(), '160');
  await stage.hover(); await page.mouse.wheel(0, -120);
  assert.equal(await page.locator('#r-avatar-zoom').inputValue(), '165');
  await page.locator('#cancel-r-avatar-editor').click();
  assert.deepEqual(await read(), saved, 'Cancel keeps the saved crop');
  await page.reload();
  await page.locator('.r-id-photo img').waitFor();
  assert.equal((await read()).zoom, 160);
  await page.setViewportSize({width: 390, height: 844});
  await page.locator('#r-edit-photo').click();
  await page.waitForFunction(() => !document.querySelector('#save-r-avatar-editor').disabled);
  const modal = await page.locator('#r-avatar-editor').boundingBox();
  assert.ok(modal.x >= 0 && modal.x + modal.width <= 391 && modal.y >= 0 && modal.y + modal.height <= 845);
  const mobileBounds = await stage.boundingBox();
  const client = await context.newCDPSession(page);
  const point = {x: mobileBounds.x + mobileBounds.width / 2, y: mobileBounds.y + mobileBounds.height / 2, id: 1};
  await client.send('Input.dispatchTouchEvent', {type: 'touchStart', touchPoints: [point]});
  await client.send('Input.dispatchTouchEvent', {type: 'touchMove', touchPoints: [{...point, x: point.x - 12, y: point.y - 8}]});
  await client.send('Input.dispatchTouchEvent', {type: 'touchEnd', touchPoints: []});
  await stage.press('ArrowLeft'); await stage.press('+');
  await page.screenshot({path: 'artifacts/photo-editor/mobile-modal.png'});
  await page.locator('#save-r-avatar-editor').click();
  const adjusted = await read();
  assert.equal(adjusted.zoom, 165); assert.ok(adjusted.photoX < saved.photoX && adjusted.photoY < saved.photoY);
  await upload();
  await page.locator('#close-r-avatar-editor').click();
  assert.deepEqual(await read(), adjusted, 'Cancel replacement keeps the original photo');
  await page.setViewportSize({width: 1440, height: 1000});
  await page.locator('#career-tab').click();
  await page.waitForFunction(() => document.querySelector('#resume-preview').dataset.fontStatus === 'ready');
  await page.locator('#edit-avatar').click();
  assert.equal(await page.locator('#avatar-editor').isVisible(), true);
  assert.equal(await page.locator('#avatar-editor input[name="avatar-shape"]').count(), 2);
  await page.locator('#cancel-avatar-editor').click();
  await page.locator('#personal-tab').click();
  assert.deepEqual(await read(), adjusted, 'The career photo editor does not change the ID photo');
  await page.locator('#r-photo').setInputFiles({name: 'broken.png', mimeType: 'image/png', buffer: Buffer.from('invalid image')});
  await page.waitForFunction(() => document.querySelector('#r-status').textContent.includes('无法读取'));
  assert.deepEqual(await read(), adjusted);
  await page.pdf({path: 'artifacts/photo-editor/cropped-photo.pdf', format: 'A4', preferCSSPageSize: true, printBackground: true});
  await page.locator('#r-remove-photo').click();
  assert.equal(await page.locator('#r-edit-photo').isDisabled(), true);
  assert.equal(await page.locator('.r-id-photo img').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Passed: upload/cancel, drag, zoom, keyboard, mobile touch, matching crop, persistence, replacement, separate career editor, invalid image and removal');
  await browser.close();
})().catch(error => {console.error(error); process.exit(1);});
